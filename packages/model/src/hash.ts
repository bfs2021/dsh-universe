// Seeded randomness. Same inputs, same numbers, on every machine.

/** mulberry32: a small seeded generator returning [0, 1). */
export function rng(seed: number): () => number {
  let s = seed | 0;
  return () => {
    s = (s + 0x6d2b79f5) | 0;
    let x = Math.imul(s ^ (s >>> 15), 1 | s);
    x = (x + Math.imul(x ^ (x >>> 7), 61 | x)) ^ x;
    return ((x ^ (x >>> 14)) >>> 0) / 4294967296;
  };
}

/** A hash of three integers to [0, 1). */
export function hs(a: number, b: number, c: number): number {
  let h = (Math.imul(a | 0, 374761393) + Math.imul(b | 0, 668265263) + Math.imul(c | 0, 1274126177)) | 0;
  h = Math.imul(h ^ (h >>> 13), 1274126177);
  return ((h ^ (h >>> 16)) >>> 0) / 4294967296;
}

/** The main colour of a session's tower (0–8, an index into the art kit's bold colours), from its seed. */
export const hueOf = (seed: number) => (Math.floor(hs(seed | 0, 11, 3) * 1e6) >> 12) % 9;

/** FNV-1a over a string: the numeric seed of a session id. */
export function seedOf(id: string): number {
  let h = 0x811c9dc5;
  for (let i = 0; i < id.length; i++) {
    h ^= id.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return h >>> 0;
}
